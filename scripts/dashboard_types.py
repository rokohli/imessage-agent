"""Generate the small dashboard schema interface from FastAPI, without Node tooling."""
import json
import sys
from pathlib import Path
from tempfile import TemporaryDirectory
from imessage_agent.dashboard import create_app


def typescript(schema):
    if '$ref' in schema:
        return "components['schemas'][" + json.dumps(schema['$ref'].split('/')[-1]) + ']'
    if 'anyOf' in schema:
        return ' | '.join(typescript(part) for part in schema['anyOf'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    if 'const' in schema:
        return json.dumps(schema['const'])
    kind = schema.get('type')
    if kind == 'array':
        return '(' + typescript(schema['items']) + ')[]'
    if kind == 'object':
        required = schema.get('required', [])
        return '{' + '; '.join(json.dumps(k) + ('' if k in required else '?') + ': ' + typescript(v)
                               for k, v in schema.get('properties', {}).items()) + '}'
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean',
            'null': 'null'}.get(kind, 'unknown')


if __name__ == '__main__':
    assert typescript({'anyOf': [{'type': 'string'}, {'type': 'null'}]}) == 'string | null'
    with TemporaryDirectory() as directory:
        schemas = create_app(Path(directory) / 'state.sqlite3').openapi()['components']['schemas']
    output = '// Generated by scripts/dashboard_types.py; do not edit.\nexport interface components {schemas: {\n'
    output += '\n'.join(json.dumps(k) + ': ' + typescript(v) + ';' for k, v in schemas.items())
    output += '\n}}\n'
    target = Path(__file__).resolve().parents[1] / 'dashboard/src/schema.ts'
    if '--check' in sys.argv:
        raise SystemExit(target.read_text() != output)
    target.write_text(output)
